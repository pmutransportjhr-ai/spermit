CREATE OR ALTER PROCEDURE dbo.SP_MISC_PAYMENT_REASON_AED
    @MODE VARCHAR(30),
    @AUTHORITY_CODE VARCHAR(3)=NULL,
    @REASON_ID INT=NULL,
    @REASON_CODE VARCHAR(40)=NULL,
    @REASON_NAME NVARCHAR(200)=NULL,
    @AMOUNT_MODE VARCHAR(10)=NULL,
    @FIXED_AMOUNT DECIMAL(18,2)=NULL,
    @IS_ACTIVE BIT=NULL,
    @DISPLAY_ORDER INT=NULL,
    @FIELD_KEY VARCHAR(50)=NULL,
    @FIELD_LABEL NVARCHAR(150)=NULL,
    @FIELD_TYPE VARCHAR(20)=NULL,
    @IS_REQUIRED BIT=NULL,
    @FIELD_OPTIONS NVARCHAR(1000)=NULL,
    @FIELD_ID INT=NULL
AS
BEGIN
    SET NOCOUNT ON;
    IF @MODE='LIST_AUTHORITIES'
        SELECT AUTHORITY_CODE,AUTHORITY_NAME FROM dbo.MISC_PAYMENT_AUTHORITY_MASTER WHERE IS_ACTIVE=1 ORDER BY AUTHORITY_NAME;
    ELSE IF @MODE='LIST_REASONS'
        SELECT REASON_ID,REASON_CODE,REASON_NAME,AMOUNT_MODE,FIXED_AMOUNT
        FROM dbo.MISC_PAYMENT_REASON_MASTER
        WHERE AUTHORITY_CODE=@AUTHORITY_CODE AND IS_ACTIVE=1
        ORDER BY DISPLAY_ORDER,REASON_NAME;
    ELSE IF @MODE='LIST_FIELDS'
        SELECT FIELD_ID,FIELD_KEY,FIELD_LABEL,FIELD_TYPE,IS_REQUIRED,FIELD_OPTIONS
        FROM dbo.MISC_PAYMENT_REASON_FIELD_MASTER
        WHERE REASON_ID=@REASON_ID AND IS_ACTIVE=1
        ORDER BY DISPLAY_ORDER,FIELD_ID;
    ELSE IF @MODE='SAVE_REASON'
    BEGIN
        IF @AUTHORITY_CODE NOT IN ('STA','RTA') OR NULLIF(LTRIM(RTRIM(@REASON_CODE)),'') IS NULL OR NULLIF(LTRIM(RTRIM(@REASON_NAME)),'') IS NULL
            THROW 51001,'Invalid miscellaneous payment reason.',1;
        IF @AMOUNT_MODE NOT IN ('FIXED','VARIABLE') THROW 51002,'Invalid amount mode.',1;
        IF @AMOUNT_MODE='FIXED' AND ISNULL(@FIXED_AMOUNT,0)<=0 THROW 51003,'Fixed amount must be greater than zero.',1;
        IF ISNULL(@REASON_ID,0)=0
            INSERT dbo.MISC_PAYMENT_REASON_MASTER(AUTHORITY_CODE,REASON_CODE,REASON_NAME,AMOUNT_MODE,FIXED_AMOUNT,IS_ACTIVE,DISPLAY_ORDER)
            VALUES(@AUTHORITY_CODE,@REASON_CODE,@REASON_NAME,@AMOUNT_MODE,@FIXED_AMOUNT,ISNULL(@IS_ACTIVE,1),ISNULL(@DISPLAY_ORDER,0));
        ELSE
            UPDATE dbo.MISC_PAYMENT_REASON_MASTER SET AUTHORITY_CODE=@AUTHORITY_CODE,REASON_CODE=@REASON_CODE,REASON_NAME=@REASON_NAME,
                AMOUNT_MODE=@AMOUNT_MODE,FIXED_AMOUNT=@FIXED_AMOUNT,IS_ACTIVE=ISNULL(@IS_ACTIVE,IS_ACTIVE),DISPLAY_ORDER=ISNULL(@DISPLAY_ORDER,DISPLAY_ORDER)
            WHERE REASON_ID=@REASON_ID;
        SELECT ISNULL(@REASON_ID,SCOPE_IDENTITY()) AS REASON_ID;
    END
    ELSE IF @MODE='SAVE_FIELD'
    BEGIN
        IF @FIELD_TYPE NOT IN ('TEXT','NUMBER','DATE','DROPDOWN','TEXTAREA') THROW 51004,'Invalid field type.',1;
        IF ISNULL(@FIELD_ID,0)=0
            INSERT dbo.MISC_PAYMENT_REASON_FIELD_MASTER(REASON_ID,FIELD_KEY,FIELD_LABEL,FIELD_TYPE,IS_REQUIRED,FIELD_OPTIONS,DISPLAY_ORDER,IS_ACTIVE)
            VALUES(@REASON_ID,@FIELD_KEY,@FIELD_LABEL,@FIELD_TYPE,ISNULL(@IS_REQUIRED,0),@FIELD_OPTIONS,ISNULL(@DISPLAY_ORDER,0),1);
        ELSE
            UPDATE dbo.MISC_PAYMENT_REASON_FIELD_MASTER SET FIELD_KEY=@FIELD_KEY,FIELD_LABEL=@FIELD_LABEL,FIELD_TYPE=@FIELD_TYPE,
                IS_REQUIRED=ISNULL(@IS_REQUIRED,IS_REQUIRED),FIELD_OPTIONS=@FIELD_OPTIONS,DISPLAY_ORDER=ISNULL(@DISPLAY_ORDER,DISPLAY_ORDER)
            WHERE FIELD_ID=@FIELD_ID AND REASON_ID=@REASON_ID;
        SELECT ISNULL(@FIELD_ID,SCOPE_IDENTITY()) AS FIELD_ID;
    END
    ELSE THROW 51005,'Unsupported SP_MISC_PAYMENT_REASON_AED mode.',1;
END;
GO

CREATE OR ALTER PROCEDURE dbo.SP_MISC_PAYMENT_TRANSACTION_AED
    @MODE VARCHAR(30),
    @DEPTTRANID VARCHAR(40)=NULL,
    @APP_ID INT=NULL,
    @APPLICATION_NUMBER VARCHAR(120)=NULL,
    @APPLICANT_NAME NVARCHAR(200)=NULL,
    @AUTHORITY_CODE VARCHAR(3)=NULL,
    @REASON_ID INT=NULL,
    @AMOUNT DECIMAL(18,2)=NULL,
    @ADDITIONAL_FIELDS_JSON NVARCHAR(MAX)=NULL,
    @TRN_STATUS VARCHAR(20)=NULL,
    @TRN_MESSAGE NVARCHAR(1000)=NULL,
    @TRN_REF_NO VARCHAR(100)=NULL,
    @PAY_MODE VARCHAR(50)=NULL,
    @TXN_DATE DATETIME2(0)=NULL,
    @TXN_AMOUNT DECIMAL(18,2)=NULL,
    @CHALLAN_URL NVARCHAR(1000)=NULL,
    @GRN VARCHAR(100)=NULL,
    @CIN VARCHAR(100)=NULL,
    @DEPTID VARCHAR(20)=NULL,
    @RECEIPTHEADCODE VARCHAR(30)=NULL,
    @PANNO VARCHAR(20)=NULL,
    @TREASCODE VARCHAR(20)=NULL,
    @IFMSOFFICECODE VARCHAR(30)=NULL,
    @ADDINFO5 NVARCHAR(500)=NULL
AS
BEGIN
    SET NOCOUNT ON;
    IF @MODE='CREATE'
    BEGIN
        IF NULLIF(@DEPTTRANID,'') IS NULL OR @APP_ID IS NULL OR @APP_ID<=0 OR NULLIF(@APPLICATION_NUMBER,'') IS NULL
            THROW 51101,'Application and department transaction details are required.',1;
        IF @AMOUNT IS NULL OR @AMOUNT<=0 THROW 51102,'Payment amount must be greater than zero.',1;
        IF @ADDITIONAL_FIELDS_JSON IS NOT NULL AND ISJSON(@ADDITIONAL_FIELDS_JSON)<>1 THROW 51103,'Invalid additional payment details.',1;
        DECLARE @REASON_NAME NVARCHAR(200);
        SELECT @REASON_NAME=REASON_NAME FROM dbo.MISC_PAYMENT_REASON_MASTER
        WHERE REASON_ID=@REASON_ID AND AUTHORITY_CODE=@AUTHORITY_CODE AND IS_ACTIVE=1;
        IF @REASON_NAME IS NULL THROW 51104,'Selected payment reason is not active for this authority.',1;
        INSERT dbo.MISC_PAYMENT_TRANSACTION
        (DEPTTRANID,APP_ID,APPLICATION_NUMBER,APPLICANT_NAME,AUTHORITY_CODE,REASON_ID,REASON_NAME,AMOUNT,ADDITIONAL_FIELDS_JSON,
         OPERATION_FOR,DEPTID,RECEIPTHEADCODE,TREASCODE,IFMSOFFICECODE,TRN_STATUS)
        VALUES
        (@DEPTTRANID,@APP_ID,@APPLICATION_NUMBER,@APPLICANT_NAME,@AUTHORITY_CODE,@REASON_ID,@REASON_NAME,@AMOUNT,@ADDITIONAL_FIELDS_JSON,
         @REASON_NAME,@DEPTID,@RECEIPTHEADCODE,@TREASCODE,@IFMSOFFICECODE,'INITIATED');
        SELECT * FROM dbo.MISC_PAYMENT_TRANSACTION WHERE DEPTTRANID=@DEPTTRANID;
    END
    ELSE IF @MODE='MARK_REQUESTED'
    BEGIN
        UPDATE dbo.MISC_PAYMENT_TRANSACTION
        SET TRN_STATUS='REQUESTED',UPDATED_ON=SYSDATETIME()
        WHERE DEPTTRANID=@DEPTTRANID AND TRN_STATUS='INITIATED';
        IF @@ROWCOUNT=0 THROW 51108,'Payment request was already submitted or is no longer available.',1;
        SELECT * FROM dbo.MISC_PAYMENT_TRANSACTION WHERE DEPTTRANID=@DEPTTRANID;
    END
    ELSE IF @MODE='GET_BY_DEPTTRANID'
        SELECT T.*,A.DEPTID AS CFG_DEPTID,A.RECEIPTHEADCODE AS CFG_RECEIPTHEADCODE,A.TREASCODE AS CFG_TREASCODE,A.IFMSOFFICECODE AS CFG_IFMSOFFICECODE
        FROM dbo.MISC_PAYMENT_TRANSACTION T
        INNER JOIN dbo.MISC_PAYMENT_AUTHORITY_MASTER A ON A.AUTHORITY_CODE=T.AUTHORITY_CODE
        WHERE T.DEPTTRANID=@DEPTTRANID;
    ELSE IF @MODE='UPDATE_RESPONSE'
    BEGIN
        UPDATE dbo.MISC_PAYMENT_TRANSACTION
        SET TRN_STATUS=@TRN_STATUS,TRN_MESSAGE=@TRN_MESSAGE,TRN_REF_NO=@TRN_REF_NO,PAY_MODE=@PAY_MODE,
            TXN_DATE=@TXN_DATE,TXN_AMOUNT=@TXN_AMOUNT,CHALLAN_URL=@CHALLAN_URL,GRN=@GRN,CIN=@CIN,
            DEPTID=@DEPTID,RECEIPTHEADCODE=@RECEIPTHEADCODE,PANNO=@PANNO,TREASCODE=@TREASCODE,
            IFMSOFFICECODE=@IFMSOFFICECODE,ADDINFO5=@ADDINFO5,UPDATED_ON=SYSDATETIME()
        WHERE DEPTTRANID=@DEPTTRANID AND TRN_STATUS IN ('INITIATED','REQUESTED','BOOKED','FAIL');
        IF @@ROWCOUNT=0 AND NOT EXISTS(SELECT 1 FROM dbo.MISC_PAYMENT_TRANSACTION WHERE DEPTTRANID=@DEPTTRANID)
            THROW 51105,'Miscellaneous payment transaction not found.',1;
        SELECT * FROM dbo.MISC_PAYMENT_TRANSACTION WHERE DEPTTRANID=@DEPTTRANID;
    END
    ELSE IF @MODE='GET_BY_APPLICATION'
        SELECT * FROM dbo.MISC_PAYMENT_TRANSACTION WHERE APPLICATION_NUMBER=@APPLICATION_NUMBER ORDER BY CREATED_ON DESC;
    ELSE IF @MODE='UPDATE_VERIFICATION'
    BEGIN
        UPDATE dbo.MISC_PAYMENT_TRANSACTION
        SET TRN_STATUS=@TRN_STATUS,TRN_MESSAGE=@TRN_MESSAGE,TRN_REF_NO=COALESCE(@TRN_REF_NO,TRN_REF_NO),
            PAY_MODE=COALESCE(@PAY_MODE,PAY_MODE),TXN_DATE=COALESCE(@TXN_DATE,TXN_DATE),
            TXN_AMOUNT=COALESCE(@TXN_AMOUNT,TXN_AMOUNT),CHALLAN_URL=COALESCE(@CHALLAN_URL,CHALLAN_URL),
            GRN=COALESCE(@GRN,GRN),CIN=COALESCE(@CIN,CIN),LAST_VERIFIED_ON=SYSDATETIME(),UPDATED_ON=SYSDATETIME()
        WHERE DEPTTRANID=@DEPTTRANID AND TRN_STATUS<>'SUCCESS';
        IF @@ROWCOUNT=0 AND NOT EXISTS(SELECT 1 FROM dbo.MISC_PAYMENT_TRANSACTION WHERE DEPTTRANID=@DEPTTRANID)
            THROW 51106,'Miscellaneous payment transaction not found.',1;
        SELECT * FROM dbo.MISC_PAYMENT_TRANSACTION WHERE DEPTTRANID=@DEPTTRANID;
    END
    ELSE THROW 51107,'Unsupported SP_MISC_PAYMENT_TRANSACTION_AED mode.',1;
END;
GO

