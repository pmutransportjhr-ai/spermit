    /// <summary>
    /// Log verification result to PAYMENT_VERIFICATION_LOG table.
    /// Never throws — failures are silently ignored.
    /// </summary>
    private void LogVerificationResult(string verificationId, string applicationNumber, string appId,
        string depttranid, int dbTxnId, string currentDbStatus, string returnedStatus,
        string returnedDepttranid, string returnedGrn, string returnedAmount, decimal dbAmount,
        string verificationResult, string updateAction, string operationFor, string trType, string message)
    {
        try
        {
            string connStr = SQLHelper.GetConnString();
            using (SqlConnection conn = new SqlConnection(connStr))
            using (SqlCommand cmd = new SqlCommand(@"
                INSERT INTO PAYMENT_VERIFICATION_LOG 
                (VERIFICATION_ID, APPLICATION_NUMBER, APP_ID, DEPTTRANID, DB_TXN_ID, CURRENT_DB_STATUS,
                 RETURNED_STATUS, RETURNED_DEPTTRANID, RETURNED_GRN, RETURNED_AMOUNT, DB_AMOUNT,
                 VERIFICATION_RESULT, UPDATE_ACTION, OPERATION_FOR, TR_TYPE, MESSAGE, MACHINE_NAME)
                VALUES 
                (@VID, @APPNUM, @APPID, @DTID, @DBTXNID, @CURSTAT,
                 @RETSTAT, @RETDTID, @RETGRN, @RETAMT, @DBAMT,
                 @VRESULT, @UACTION, @OPFOR, @TRTYPE, @MSG, @MACHINE)", conn))
            {
                cmd.Parameters.AddWithValue("@VID", verificationId ?? "");
                cmd.Parameters.AddWithValue("@APPNUM", applicationNumber ?? "");
                cmd.Parameters.AddWithValue("@APPID", appId ?? "");
                cmd.Parameters.AddWithValue("@DTID", depttranid ?? "");
                cmd.Parameters.AddWithValue("@DBTXNID", dbTxnId);
                cmd.Parameters.AddWithValue("@CURSTAT", currentDbStatus ?? "");
                cmd.Parameters.AddWithValue("@RETSTAT", returnedStatus ?? "");
                cmd.Parameters.AddWithValue("@RETDTID", returnedDepttranid ?? "");
                cmd.Parameters.AddWithValue("@RETGRN", returnedGrn ?? "");
                cmd.Parameters.AddWithValue("@RETAMT", returnedAmount ?? "");
                cmd.Parameters.AddWithValue("@DBAMT", dbAmount);
                cmd.Parameters.AddWithValue("@VRESULT", verificationResult ?? "");
                cmd.Parameters.AddWithValue("@UACTION", updateAction ?? "");
                cmd.Parameters.AddWithValue("@OPFOR", operationFor ?? "");
                cmd.Parameters.AddWithValue("@TRTYPE", trType ?? "");
                cmd.Parameters.AddWithValue("@MSG", message ?? "");
                cmd.Parameters.AddWithValue("@MACHINE", Environment.MachineName ?? "");
                
                conn.Open();
                cmd.ExecuteNonQuery();
            }
        }
        catch
        {
            // Never let logging break payment processing
        }
    }
    




