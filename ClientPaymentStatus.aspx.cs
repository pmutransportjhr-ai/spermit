public partial class ClientPaymentStatus : System.Web.UI.Page
{
    protected void Page_Load(object sender, EventArgs e)
    {
        System.Net.WebClient client = new System.Net.WebClient();
        ServicePointManager.ServerCertificateValidationCallback = delegate
        {
            return true;
        };
    }

  

    protected void btnSubmit_Click(object sender, EventArgs e)
    {
         try
        {
            string verificationId = PaymentLogger.GenerateVerificationId();
            
            clsEncrypt encdept = new clsEncrypt();  // obeject of Encryption Decryption Class.
            string DecryptTrans = "";
            string EncryptResponse = "";

            string GRN1 = "";   //goverment Receipt number  (Optional)
            string DEPTID1 = "JHTD";       //department Id which is provided by Finance Dept.

            string[] handlerResponse = CryptorEngine.Decrypt(lblencyValue.Value,true).Split('~');
 
            string DEPTTRANID1 =handlerResponse[0];
            string App_id = handlerResponse[1];
            string Application_number = handlerResponse[2];
            string operation_for = handlerResponse[3];
            string tr_type = handlerResponse[4];
            // Extract the tbl_status (6th field) — BOOKED, FAIL, or SUCCESS
            string tbl_status = handlerResponse.Length > 5 ? handlerResponse[5] : "BOOKED";
            
            // ================================================================
            // PART 4 — GRN HANDLING
            // The existing implementation uses GRN1 = "" (empty) for ALL
            // double verification requests. This is the format required by
            // JEGRAS — the API looks up transactions by DEPTTRANID, not GRN.
            // PayGetWayDTO.MakeEncrytedDataforDoubleVerification also accepts
            // GRN as a parameter but ClientPaymentStatus always passes "".
            // We preserve this behavior. The GRN is returned IN the response.
            // ================================================================
            
            // "RWD8339844111117342"; // "JHY1711131028314";// "JHY1711131025913";  //this ID is generated by Concern Portal while doing online transaction which status needs to be known.
            string SECURITYCODE1 = "sec1234";    //security key provided by Finance Department.
            string Key = "key1234";     // key provided by finance department.

            // ================================================================
            // PART 3 — Log verification context BEFORE calling JEGRAS
            // ================================================================
            PaymentLogger.LogVerificationContext(verificationId, Application_number, App_id,
                DEPTTRANID1, tbl_status, operation_for, "", "");

            String requestparameter = "";
            String EncryptTxt = "";
            requestparameter = Convert.ToString(GRN1).Trim() + "|" + DEPTID1.ToString().Trim() + "|" + DEPTTRANID1.ToString().Trim() + "|" + SECURITYCODE1.ToString().Trim();
            EncryptTxt = encdept.Encrypt(requestparameter, Key);

            // Log request (without secrets)
            PaymentLogger.GatewayRequest(verificationId, Application_number, DEPTTRANID1,
                "JEGRAS request prepared. DEPTID=" + DEPTID1 + ", GRN=" + (string.IsNullOrEmpty(GRN1) ? "(empty)" : GRN1),
                App_id, operation_for);

            string json = "";
            json = "{\"EncryptTxt\": \"" + EncryptTxt + "\",\"REQDEPTID\": \"" + DEPTID1 + "\"}";
            string verificationUrl = "https://finance.jharkhand.gov.in/JEgrasDV/JeGrasRestful.svc/SBIePayDoubleVerification";

            //create an HTTP request to the URL that we need to invoke
            System.Diagnostics.Stopwatch sw = System.Diagnostics.Stopwatch.StartNew();
            HttpWebRequest request = (HttpWebRequest)WebRequest.Create(verificationUrl);
            request.ContentType = @"application/json; charset=utf-8"; //set the content type to JSON            
            request.Timeout = 30000;
            request.Method = "POST"; //make an HTTP POST
            using (var streamWriter = new StreamWriter(request.GetRequestStream()))
            {
                //initiate the request                
                streamWriter.Write(json);
                streamWriter.Close();
            }

            WebResponse response = request.GetResponse();
            var streamReader = new StreamReader(response.GetResponseStream());
            string result = streamReader.ReadToEnd();
            sw.Stop();
            //response.Close();

            PaymentLogger.GatewayResponse(verificationId, Application_number, DEPTTRANID1,
                "JEGRAS response received in " + sw.ElapsedMilliseconds + "ms. Length=" + (result != null ? result.Length.ToString() : "0"),
                "", App_id, operation_for);

            //Encrypted Response
            EncryptResponse = result.Replace(@"\", "");
            int i = EncryptResponse.IndexOf(":") + 2;
            string actualval = EncryptResponse.Substring(i, EncryptResponse.Length - i - 2);

            //Decrypted Response
            String DecryptedVal = encdept.Decrypt(actualval, Key);
            string responseStr = DecryptTrans;
            
            PaymentLogger.Info(verificationId, Application_number, DEPTTRANID1,
                "JEGRAS_RESPONSE_DECRYPTED", "Response decrypted successfully", App_id);
           
            String[] arr;
            arr = DecryptedVal.Split('|');
            
            PaymentLogger.Info(verificationId, Application_number, DEPTTRANID1,
                "JEGRAS_RESPONSE_PARSED", "Parsed " + arr.Length + " fields from JEGRAS response", App_id);
            
            string DEPTID = arr.Length > 0 ? arr[0] : "JHTD";
            string RECIEPTHEADCODE = arr.Length > 1 ? arr[1] : "";
            string DEPOSITERNAME = arr.Length > 2 ? arr[2] : "";
            string DEPTTRANID = arr.Length > 3 ? arr[3] : DEPTTRANID1;
            
            decimal AMOUNT = 0;
            if (arr.Length > 4 && !string.IsNullOrWhiteSpace(arr[4]))
            {
                decimal.TryParse(arr[4], out AMOUNT);
            }

            string DEPOSITERID = (arr.Length > 5 && !string.IsNullOrWhiteSpace(arr[5]) && arr[5] != "NA") ? arr[5] : Application_number;   // application number
            string PANNO = arr.Length > 6 ? arr[6] : "";
            string ADDINFO1 = (arr.Length > 7 && !string.IsNullOrWhiteSpace(arr[7]) && arr[7] != "NA") ? arr[7] : operation_for;

            string ADDINFO2 = (arr.Length > 8 && !string.IsNullOrWhiteSpace(arr[8]) && arr[8] != "NA") ? arr[8] : App_id;    //app _id
            string ADDINFO3 = (arr.Length > 9 && !string.IsNullOrWhiteSpace(arr[9]) && arr[9] != "NA") ? arr[9] : tr_type;    // TR_TYPE
            string TREASCODE = arr.Length > 10 ? arr[10] : "";
            string IFMSOFFICECODE = arr.Length > 11 ? arr[11] : "";
            string STATUS = arr.Length > 12 ? arr[12] : "";
            string statusUpper = (STATUS ?? "").Trim().ToUpper();

            string PAYMENTSTATUSMESSAGE = arr.Length > 13 ? arr[13] : "";
            string GRN = arr.Length > 14 ? arr[14] : "";
            string CIN = arr.Length > 15 ? arr[15] : "";
            string REF_NO = arr.Length > 16 ? arr[16] : "";
            string TXN_DATE = arr.Length > 17 ? arr[17] : "";
            string TXN_AMOUNT = arr.Length > 18 ? arr[18] : "";
            if ((string.IsNullOrWhiteSpace(TXN_AMOUNT) || TXN_AMOUNT == "0" || TXN_AMOUNT == "0.00") && AMOUNT > 0)
            {
                TXN_AMOUNT = AMOUNT.ToString("0.00");
            }

            string CHALLAN_URL = arr.Length > 19 ? arr[19] : "";
            string PMODE = arr.Length > 20 ? arr[20] : "";
            string ADDINFO5 = arr.Length > 21 ? arr[21] : "";

            // ================================================================
            // PART 5 — DEPTTRANID VALIDATION
            // Verify that the returned DEPTTRANID matches what we requested
            // ================================================================
            string returnedDeptTranId = (DEPTTRANID ?? "").Trim();
            string requestedDeptTranId = (DEPTTRANID1 ?? "").Trim();
            
            if (!string.IsNullOrEmpty(returnedDeptTranId) && !string.IsNullOrEmpty(requestedDeptTranId)
                && returnedDeptTranId != requestedDeptTranId)
            {
                PaymentLogger.Error(verificationId, Application_number, DEPTTRANID1,
                    "TRANSACTION_ID_VALIDATED", 
                    "DEPTTRANID MISMATCH! Requested=" + requestedDeptTranId + " Returned=" + returnedDeptTranId + " — ABORTING UPDATE",
                    App_id, statusUpper, operation_for);
                
                // Log to verification table
                LogVerificationResult(verificationId, Application_number, App_id, DEPTTRANID1, 0,
                    tbl_status, statusUpper, returnedDeptTranId, GRN, TXN_AMOUNT, 0, "MISMATCH", "MISMATCH_BLOCKED",
                    operation_for, tr_type, "DEPTTRANID mismatch: requested " + requestedDeptTranId + " got " + returnedDeptTranId);
                
                ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                    "$('#loadingmessage').modal('hide');alert('Payment verification error: Transaction ID mismatch. Please contact support.');window.location ='PermitHomepage.aspx';", true);
                return;
            }
            
            PaymentLogger.Info(verificationId, Application_number, DEPTTRANID1,
                "TRANSACTION_ID_VALIDATED", "DEPTTRANID match confirmed: " + returnedDeptTranId, App_id);

            // ================================================================
            // PART 5 — AMOUNT VALIDATION  
            // Compare returned amount with expected amount (when available)
            // ================================================================
            decimal returnedAmountDecimal = 0;
            if (!string.IsNullOrWhiteSpace(TXN_AMOUNT))
                decimal.TryParse(TXN_AMOUNT, out returnedAmountDecimal);
            
            // We only block if BOTH amounts are available and nonzero and they differ
            if (AMOUNT > 0 && returnedAmountDecimal > 0 && AMOUNT != returnedAmountDecimal
                && statusUpper == "SUCCESS")
            {
                PaymentLogger.Warning(verificationId, Application_number, DEPTTRANID1,
                    "AMOUNT_VALIDATED", 
                    "AMOUNT MISMATCH! Expected=" + AMOUNT.ToString("0.00") + " Returned=" + returnedAmountDecimal.ToString("0.00") + " — BLOCKING SUCCESS UPDATE",
                    App_id, statusUpper, operation_for);
                
                LogVerificationResult(verificationId, Application_number, App_id, DEPTTRANID1, 0,
                    tbl_status, statusUpper, returnedDeptTranId, GRN, TXN_AMOUNT, AMOUNT, "MISMATCH", "MISMATCH_BLOCKED",
                    operation_for, tr_type, "Amount mismatch: expected " + AMOUNT.ToString("0.00") + " got " + returnedAmountDecimal.ToString("0.00"));
                
                ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                    "$('#loadingmessage').modal('hide');alert('Payment verification error: Amount mismatch. Please contact support.');window.location ='PermitHomepage.aspx';", true);
                return;
            }
            
            if (AMOUNT > 0 || returnedAmountDecimal > 0)
            {
                PaymentLogger.Info(verificationId, Application_number, DEPTTRANID1,
                    "AMOUNT_VALIDATED", "Amount check passed. DB=" + AMOUNT.ToString("0.00") + " Returned=" + returnedAmountDecimal.ToString("0.00"), App_id);
            }

            // ================================================================
            // PART 6 — STATUS MAPPING (Status-first, deterministic)
            // Use explicit status handling. Message-based checks are only
            // used as SUPPORTING information, not primary decision maker.
            // ================================================================
            if (statusUpper == "SUCCESS" || statusUpper == "SUCCESSFUL")
            {
                STATUS = "SUCCESS";
            }
            else if (statusUpper == "BOOKED")
            {
                STATUS = "BOOKED";
            }
            else if (statusUpper == "FAIL")
            {
                // STATUS is FAIL from JEGRAS — use the explicit status
                TXN_DATE = DateTime.Now.ToString("yyyy-MM-dd hh:mm:ss");
                TXN_AMOUNT = "0";
                ADDINFO2 = App_id;
                DEPOSITERID = Application_number;
                ADDINFO1 = operation_for;
                ADDINFO3 = tr_type;
                STATUS = "FAIL";
            }
            else
            {
                // Unknown status — log warning, treat as verification error
                // Do NOT overwrite a valid existing status
                PaymentLogger.Warning(verificationId, Application_number, DEPTTRANID1,
                    "JEGRAS_RESPONSE_PARSED", 
                    "Unknown JEGRAS status: '" + statusUpper + "' Message: " + PAYMENTSTATUSMESSAGE + " — treating as VERIFICATION_ERROR",
                    App_id, statusUpper, operation_for);
                
                LogVerificationResult(verificationId, Application_number, App_id, DEPTTRANID1, 0,
                    tbl_status, statusUpper, returnedDeptTranId, GRN, TXN_AMOUNT, AMOUNT, "VERIFICATION_ERROR", "NO_CHANGE",
                    operation_for, tr_type, "Unknown JEGRAS status: " + statusUpper);
                
                ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                    "$('#loadingmessage').modal('hide');alert('Payment verification returned an unexpected status. Please try again later or contact support.');window.location ='PermitHomepage.aspx';", true);
                return;
            }
            
            PaymentLogger.Info(verificationId, Application_number, DEPTTRANID1,
                "FINAL_PAYMENT_STATUS", 
                "JEGRAS STATUS=" + STATUS + " | MSG=" + PAYMENTSTATUSMESSAGE + " | GRN=" + GRN + " | REF=" + REF_NO + " | TXN_DATE=" + TXN_DATE + " | TXN_AMT=" + TXN_AMOUNT,
                App_id, STATUS, operation_for);

            // ================================================================
            // PART 7 & 8 — DATABASE UPDATE
            // For FAIL re-verifications (tbl_status == "FAIL"), use 
            // SP_PAYMENT_VERIFICATION_UPDATE which:
            //   - Updates by DEPTTRANID (correct transaction)
            //   - Prevents SUCCESS→FAIL downgrade
            //   - Does not insert duplicate rows
            //
            // For BOOKED/SUCCESS (original flow), use existing 
            // AddTransactionDetails to preserve backward compatibility.
            // ================================================================
            String[] aa = new string[3];
            String MSG;
            
            if (tbl_status == "FAIL")
            {
                // ── Re-verification of a previously FAILED transaction ──
                PaymentLogger.DatabaseUpdate(verificationId, Application_number, DEPTTRANID1,
                    "DATABASE_UPDATE_STARTED", "Updating FAIL transaction via SP_PAYMENT_VERIFICATION_UPDATE",
                    App_id, "FAIL", STATUS, operation_for);
                
                try
                {
                    string connStr = SQLHelper.GetConnString();
                    using (SqlConnection conn = new SqlConnection(connStr))
                    using (SqlCommand cmd = new SqlCommand("SP_PAYMENT_VERIFICATION_UPDATE", conn))
                    {
                        cmd.CommandType = CommandType.StoredProcedure;
                        cmd.Parameters.AddWithValue("@DEPTTRANID", DEPTTRANID1);
                        cmd.Parameters.AddWithValue("@APPLICATION_NUMBER", Application_number);
                        cmd.Parameters.AddWithValue("@NEW_STATUS", STATUS);
                        cmd.Parameters.AddWithValue("@TRN_MESSAGE", PAYMENTSTATUSMESSAGE);
                        cmd.Parameters.AddWithValue("@TRN_REF_NO", REF_NO);
                        cmd.Parameters.AddWithValue("@GRN", GRN);
                        cmd.Parameters.AddWithValue("@CIN", CIN);
                        cmd.Parameters.AddWithValue("@TXN_DATE", TXN_DATE);
                        cmd.Parameters.AddWithValue("@TXN_AMOUNT", TXN_AMOUNT);
                        cmd.Parameters.AddWithValue("@CHALLAN_URL", CHALLAN_URL);
                        cmd.Parameters.AddWithValue("@PAY_MODE", PMODE);
                        cmd.Parameters.AddWithValue("@DEPTID", DEPTID);
                        cmd.Parameters.AddWithValue("@RECIEPTHEADCODE", RECIEPTHEADCODE);
                        cmd.Parameters.AddWithValue("@TREASCODE", TREASCODE);
                        cmd.Parameters.AddWithValue("@IFMSOFFICECODE", IFMSOFFICECODE);
                        cmd.Parameters.AddWithValue("@VERIFICATION_ID", verificationId);
                        cmd.Parameters.AddWithValue("@MODE", "UPDATE");
                        
                        DataSet updateDs = new DataSet();
                        SqlDataAdapter updateDa = new SqlDataAdapter(cmd);
                        updateDa.Fill(updateDs);
                        
                        string updateResult = "ERROR";
                        string currentDbStatus = "";
                        if (updateDs.Tables.Count > 0 && updateDs.Tables[0].Rows.Count > 0)
                        {
                            updateResult = Convert.ToString(updateDs.Tables[0].Rows[0]["RESULT"]);
                            currentDbStatus = Convert.ToString(updateDs.Tables[0].Rows[0]["CURRENT_STATUS"]);
                        }
                        
                        PaymentLogger.DatabaseUpdate(verificationId, Application_number, DEPTTRANID1,
                            "DATABASE_UPDATE_COMPLETED", "SP result: " + updateResult,
                            App_id, currentDbStatus, STATUS, operation_for);
                        
                        // Log to verification table
                        LogVerificationResult(verificationId, Application_number, App_id, DEPTTRANID1, 0,
                            "FAIL", STATUS, returnedDeptTranId, GRN, TXN_AMOUNT, AMOUNT, 
                            STATUS == "SUCCESS" ? "VERIFIED_SUCCESS" : (STATUS == "FAIL" ? "VERIFIED_FAIL" : "VERIFIED_BOOKED"),
                            updateResult, operation_for, tr_type, "JEGRAS: " + PAYMENTSTATUSMESSAGE);
                        
                        if (updateResult == "BLOCKED_DOWNGRADE")
                        {
                            // Transaction was already SUCCESS — don't downgrade
                            PaymentLogger.Warning(verificationId, Application_number, DEPTTRANID1,
                                "DATABASE_UPDATE_COMPLETED", "Downgrade blocked: transaction already SUCCESS, JEGRAS returned FAIL",
                                App_id, "SUCCESS", operation_for);
                            ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                                "$('#loadingmessage').modal('hide');alert('Your payment has already been verified as SUCCESS.');window.location ='PermitHomepage.aspx';", true);
                            return;
                        }
                        else if (updateResult == "ALREADY_SUCCESS")
                        {
                            ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                                "$('#loadingmessage').modal('hide');alert('Your payment has already been verified as SUCCESS.');window.location ='PermitHomepage.aspx';", true);
                            return;
                        }
                        else if (updateResult == "NOT_FOUND")
                        {
                            PaymentLogger.Error(verificationId, Application_number, DEPTTRANID1,
                                "DATABASE_UPDATE_FAILED", "Transaction not found in DB for DEPTTRANID",
                                App_id, "", operation_for);
                            ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                                "$('#loadingmessage').modal('hide');alert('Transaction record not found. Please contact support.');window.location ='PermitHomepage.aspx';", true);
                            return;
                        }
                        else if (updateResult == "UPDATE_ERROR")
                        {
                            PaymentLogger.Error(verificationId, Application_number, DEPTTRANID1,
                                "DATABASE_UPDATE_FAILED", "SP_PAYMENT_VERIFICATION_UPDATE returned UPDATE_ERROR",
                                App_id, "", operation_for);
                            ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                                "$('#loadingmessage').modal('hide');alert('!Opps something happens wrong. try again later');window.location ='PermitHomepage.aspx';", true);
                            return;
                        }
                        
                        // Update succeeded — determine navigation
                        if (STATUS == "SUCCESS")
                        {
                            // Re-verification changed FAIL → SUCCESS
                            // Use existing AddTransactionDetails to get the receipt page URL
                            if (ADDINFO1 == "STA COUNTER SIGNATURE TAX PAY" || (ADDINFO3 != null && ADDINFO3.StartsWith("STA-APPLICATION_") && ADDINFO3.Split('_').Length >= 3))
                            {
                                aa = ADDINFO3.Split('_');
                                MSG = PaymentTransaction.AddTransactionDetails(ADDINFO2, DEPOSITERID, DEPOSITERNAME, AMOUNT, ADDINFO1, STATUS, PAYMENTSTATUSMESSAGE, REF_NO, PMODE, "", TXN_DATE, TXN_AMOUNT, CHALLAN_URL, GRN, CIN, DEPTID, RECIEPTHEADCODE, DEPTTRANID, PANNO, aa[0], TREASCODE, IFMSOFFICECODE, ADDINFO5, aa[1], aa[2]);
                            }
                            else
                            {
                                MSG = PaymentTransaction.AddTransactionDetails(ADDINFO2, DEPOSITERID, DEPOSITERNAME, AMOUNT, ADDINFO1, STATUS, PAYMENTSTATUSMESSAGE, REF_NO, PMODE, "", TXN_DATE, TXN_AMOUNT, CHALLAN_URL, GRN, CIN, DEPTID, RECIEPTHEADCODE, DEPTTRANID, PANNO, ADDINFO3, TREASCODE, IFMSOFFICECODE, ADDINFO5, "", "");
                            }
                            
                            if (MSG != null && MSG.Contains(".aspx"))
                            {
                                if (ADDINFO1 == "STA COUNTER SIGNATURE TAX PAY")
                                {
                                    aa = ADDINFO3.Split('_');
                                    string targetUrl = MSG.Split('~')[0];
                                    string tblType = MSG.Split('~').Length > 1 ? MSG.Split('~')[1] : (aa.Length > 2 ? aa[2] : "");
                                    ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), "$('#loadingmessage').modal('hide');alert('Payment verified successfully! The tax has been successfully paid');window.location ='" + targetUrl + "?q=" + HttpUtility.UrlEncode(CryptorEngine.Encrypt("APP_ID=" + Convert.ToString(ADDINFO2) + "&GRN=" + Convert.ToString(GRN) + "&TBL=" + tblType + "&TYPE=" + ADDINFO3 + "&APPLICATION_SERVICE=" + Convert.ToString(ADDINFO1), true), Response.ContentEncoding) + "'", true);
                                }
                                else
                                {
                                    ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), "$('#loadingmessage').modal('hide');alert('Payment verified successfully! The tax has been successfully paid');window.location ='" + MSG + "?q=" + HttpUtility.UrlEncode(CryptorEngine.Encrypt("APP_ID=" + Convert.ToString(ADDINFO2) + "&TYPE=" + Convert.ToString(arr[9]) + "&APPLICATION_SERVICE=" + Convert.ToString(ADDINFO1), true), Response.ContentEncoding) + "'", true);
                                }
                            }
                            else
                            {
                                ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                                    "$('#loadingmessage').modal('hide');alert('Payment has been verified as SUCCESS. Please check your application status.');window.location ='PermitHomepage.aspx';", true);
                            }
                            return;
                        }
                        else if (STATUS == "FAIL")
                        {
                            ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                                "$('#loadingmessage').modal('hide');alert('Your payment status is : FAILED. " + PAYMENTSTATUSMESSAGE.Replace("'", "") + " Please Click on Track Application Status on Home Pages.');window.location ='PermitHomepage.aspx';", true);
                            return;
                        }
                        else if (STATUS == "BOOKED")
                        {
                            ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                                "$('#loadingmessage').modal('hide');alert('Your payment status is : BOOKED. Please Click on Track Application Status on Home Pages.');window.location ='PermitHomepage.aspx';", true);
                            return;
                        }
                    }
                }
                catch (Exception verEx)
                {
                    PaymentLogger.Error(verificationId, Application_number, DEPTTRANID1,
                        "DATABASE_UPDATE_FAILED", "Verification update exception: " + verEx.Message,
                        App_id, "", operation_for);
                    ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), 
                        "$('#loadingmessage').modal('hide');alert('!Opps something happens wrong. try again later');window.location ='PermitHomepage.aspx';", true);
                    return;
                }
            }
            else
            {
                // ── Original flow for BOOKED/SUCCESS (unchanged logic) ──
                PaymentLogger.DatabaseUpdate(verificationId, Application_number, DEPTTRANID1,
                    "DATABASE_UPDATE_STARTED", "Processing via AddTransactionDetails (tbl_status=" + tbl_status + ")",
                    App_id, tbl_status, STATUS, operation_for);
                
                if (ADDINFO1 == "STA COUNTER SIGNATURE TAX PAY" || (ADDINFO3 != null && ADDINFO3.StartsWith("STA-APPLICATION_") && ADDINFO3.Split('_').Length >= 3))
                {
                    aa = ADDINFO3.Split('_');
                    MSG = PaymentTransaction.AddTransactionDetails(ADDINFO2, DEPOSITERID, DEPOSITERNAME, AMOUNT, ADDINFO1, STATUS, PAYMENTSTATUSMESSAGE, REF_NO, PMODE, "", TXN_DATE, TXN_AMOUNT, CHALLAN_URL, GRN, CIN, DEPTID, RECIEPTHEADCODE, DEPTTRANID, PANNO, aa[0], TREASCODE, IFMSOFFICECODE, ADDINFO5, aa[1], aa[2]);
                }
                else
                {
                    MSG = PaymentTransaction.AddTransactionDetails(ADDINFO2, DEPOSITERID, DEPOSITERNAME, AMOUNT, ADDINFO1, STATUS, PAYMENTSTATUSMESSAGE, REF_NO, PMODE, "", TXN_DATE, TXN_AMOUNT, CHALLAN_URL, GRN, CIN, DEPTID, RECIEPTHEADCODE, DEPTTRANID, PANNO, ADDINFO3, TREASCODE, IFMSOFFICECODE, ADDINFO5, "", "");
                }
                
                PaymentLogger.DatabaseUpdate(verificationId, Application_number, DEPTTRANID1,
                    "DATABASE_UPDATE_COMPLETED", "AddTransactionDetails returned: " + (MSG ?? "null"),
                    App_id, tbl_status, STATUS, operation_for);
                
                if (MSG == "Error")
                {
                    PaymentLogger.Error(verificationId, Application_number, DEPTTRANID1,
                        "DATABASE_UPDATE_FAILED", "AddTransactionDetails returned Error",
                        App_id, "", operation_for);
                    ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), "$('#loadingmessage').modal('hide');alert('!Opps something happens wrong. try again later');window.location ='PermitHomepage.aspx';", true);
                    return;
                }
                else if (MSG == "BOOKED" || MSG == "FAIL")
                {
                    MSG = MSG == "FAIL" ? "FAILED" : "BOOKED";
                    ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), "$('#loadingmessage').modal('hide');alert('Your payment status is : " + MSG + ". Please Click on Track Application Status on Home Pages.');window.location ='PermitHomepage.aspx';", true);
                    return;
                }
                else if(MSG.Contains(".aspx"))
                {
                    if (ADDINFO1 == "STA COUNTER SIGNATURE TAX PAY")
                    {
                        aa = ADDINFO3.Split('_');
                        string targetUrl = MSG.Split('~')[0];
                        string tblType = MSG.Split('~').Length > 1 ? MSG.Split('~')[1] : (aa.Length > 2 ? aa[2] : "");
                        ScriptManager.RegisterClientScriptBlock((sender as Control), this.GetType(), Guid.NewGuid().ToString(), "$('#loadingmessage').modal('hide');alert('The tax has been successfully paid');window.location ='" + targetUrl + "?q=" + HttpUtility.UrlEncode(CryptorEngine.Encrypt("APP_ID=" + Convert.ToString(ADDINFO2) + "&GRN=" + Convert.ToString(GRN) + "&TBL=" + tblType + "&TYPE=" + ADDINFO3 + "&APPLICATION_SERVICE=" + Convert.ToString(ADDINFO1), true), Response.ContentEncoding) + "'", true);
                        return;
                    }
                    else
                    {
